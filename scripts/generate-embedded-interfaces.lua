static int titan_ls_push_current_executable(lua_State *L) {
    size_t capacity = 256;

    for (;;) {
        char *path = (char *)lua_newuserdatauv(L, capacity, 0);
        ssize_t length;
        int saved_errno;

        errno = 0;
        length = readlink("/proc/self/exe", path, capacity);
        saved_errno = errno;
        if (length < 0) {
            return luaL_error(L,
                "cannot read the current executable path: %s",
                saved_errno != 0 ? strerror(saved_errno) : "unknown error");
        }
        if ((size_t)length < capacity) {
            lua_pushlstring(L, path, (size_t)length);
            lua_remove(L, -2);
            return 1;
        }
        lua_pop(L, 1);
        if (capacity > SIZE_MAX / 2) {
            return luaL_error(L, "current executable path is too long");
        }
        capacity *= 2;
    }
}

