static void titan_ls_set_identity_integer(lua_State *L,
                                          const unsigned char *key,
                                          size_t key_size,
                                          lua_Integer value) {
    titan_ls_push_bytes(L, key, key_size);
    lua_pushinteger(L, value);
    lua_rawset(L, -3);
}

int titan_ls_push_embedded_provider_identity(lua_State *L) {
    struct stat metadata;
    const char *path;
    int saved_errno;
#if defined(__APPLE__)
    long modified_nanoseconds;
    int uuid_mismatch;
#endif

    luaL_checkstack(L, 5, "embedded Titan provider identity");
    titan_ls_push_current_executable(L);
    path = lua_tostring(L, -1);
    if (path == NULL) {
        return luaL_error(L, "current executable path is not a string");
    }

    errno = 0;
#if defined(__APPLE__)
    if (!titan_ls_stat_current_executable(
            path, &metadata, &uuid_mismatch)) {
        if (uuid_mismatch) {
            return luaL_error(L,
                "current executable path no longer names the running "
                "Mach-O image; restart the language server");
        }
#else
    /* Follow the live executable inode even after its launch path is
     * atomically replaced or unlinked. The returned identity still carries
     * the human-facing provider path pushed above. */
    if (stat("/proc/self/exe", &metadata) != 0) {
#endif
        saved_errno = errno;
        return luaL_error(L,
            "cannot stat the current executable: %s",
            saved_errno != 0 ? strerror(saved_errno) : "unknown error");
    }
    if (!S_ISREG(metadata.st_mode)) {
        return luaL_error(L, "current executable is not a regular file");
    }

    lua_createtable(L, 0, 7);
    titan_ls_push_bytes(L, titan_ls_identity_path_key,
                       sizeof(titan_ls_identity_path_key));
    lua_pushvalue(L, -3);
    lua_rawset(L, -3);
    titan_ls_set_identity_integer(
        L, titan_ls_identity_size_key, sizeof(titan_ls_identity_size_key),
        (lua_Integer)metadata.st_size);
    titan_ls_push_bytes(L, titan_ls_identity_kind_key,
                       sizeof(titan_ls_identity_kind_key));
    titan_ls_push_bytes(L, titan_ls_identity_file_value,
                       sizeof(titan_ls_identity_file_value));
    lua_rawset(L, -3);
    titan_ls_set_identity_integer(
        L, titan_ls_identity_device_key,
        sizeof(titan_ls_identity_device_key), (lua_Integer)metadata.st_dev);
    titan_ls_set_identity_integer(
        L, titan_ls_identity_inode_key,
        sizeof(titan_ls_identity_inode_key), (lua_Integer)metadata.st_ino);
#if defined(__APPLE__)
    titan_ls_set_identity_integer(
        L, titan_ls_identity_seconds_key,
        sizeof(titan_ls_identity_seconds_key),
        (lua_Integer)metadata.st_mtimespec.tv_sec);
    modified_nanoseconds = metadata.st_mtimespec.tv_nsec;
#else
    titan_ls_set_identity_integer(
        L, titan_ls_identity_seconds_key,
        sizeof(titan_ls_identity_seconds_key),
        (lua_Integer)metadata.st_mtim.tv_sec);
#endif
    titan_ls_set_identity_integer(
        L, titan_ls_identity_nanoseconds_key,
        sizeof(titan_ls_identity_nanoseconds_key),
#if defined(__APPLE__)
        (lua_Integer)modified_nanoseconds);
#else
        (lua_Integer)metadata.st_mtim.tv_nsec);
#endif

    lua_remove(L, -2);
    return 1;
}

