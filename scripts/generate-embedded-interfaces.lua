static int titan_ls_mapped_main_uuid(unsigned char result[16]) {
    const struct mach_header *raw_header = _dyld_get_image_header(0);
    const struct mach_header_64 *header;
    const unsigned char *cursor;
    size_t remaining;
    uint32_t index;

    if (raw_header == NULL || raw_header->magic != MH_MAGIC_64) return 0;
    header = (const struct mach_header_64 *)raw_header;
    cursor = (const unsigned char *)(header + 1);
    remaining = (size_t)header->sizeofcmds;
    for (index = 0; index < header->ncmds; ++index) {
        struct load_command command;
        if (remaining < sizeof(command)) return 0;
        memcpy(&command, cursor, sizeof(command));
        if (command.cmdsize < sizeof(command) ||
            (size_t)command.cmdsize > remaining) {
            return 0;
        }
        if (command.cmd == LC_UUID) {
            struct uuid_command uuid;
            if (command.cmdsize < sizeof(uuid)) return 0;
            memcpy(&uuid, cursor, sizeof(uuid));
            memcpy(result, uuid.uuid, sizeof(uuid.uuid));
            return 1;
        }
        cursor += command.cmdsize;
        remaining -= command.cmdsize;
    }
    return 0;
}

static int titan_ls_pread_exact(int descriptor, void *output,
                                size_t size, off_t offset) {
    size_t total = 0;
    while (total < size) {
        ssize_t count = pread(descriptor, (char *)output + total,
                              size - total, offset + (off_t)total);
        if (count < 0 && errno == EINTR) continue;
        if (count <= 0) {
            if (count == 0) errno = ENOEXEC;
            return 0;
        }
        total += (size_t)count;
    }
    return 1;
}

static int titan_ls_file_uuid(int descriptor, unsigned char result[16]) {
    struct mach_header_64 header;
    off_t offset = (off_t)sizeof(header);
    size_t remaining;
    uint32_t index;

    if (!titan_ls_pread_exact(
            descriptor, &header, sizeof(header), (off_t)0)) {
        return 0;
    }
    if (header.magic != MH_MAGIC_64) {
        errno = ENOEXEC;
        return 0;
    }
    remaining = (size_t)header.sizeofcmds;
    for (index = 0; index < header.ncmds; ++index) {
        struct load_command command;
        if (remaining < sizeof(command) ||
            !titan_ls_pread_exact(
                descriptor, &command, sizeof(command), offset)) {
            errno = ENOEXEC;
            return 0;
        }
        if (command.cmdsize < sizeof(command) ||
            (size_t)command.cmdsize > remaining) {
            errno = ENOEXEC;
            return 0;
        }
        if (command.cmd == LC_UUID) {
            struct uuid_command uuid;
            if (command.cmdsize < sizeof(uuid) ||
                !titan_ls_pread_exact(
                    descriptor, &uuid, sizeof(uuid), offset)) {
                errno = ENOEXEC;
                return 0;
            }
            memcpy(result, uuid.uuid, sizeof(uuid.uuid));
            return 1;
        }
        offset += (off_t)command.cmdsize;
        remaining -= command.cmdsize;
    }
    errno = ENOEXEC;
    return 0;
}

static int titan_ls_stat_current_executable(
        const char *path, struct stat *metadata, int *uuid_mismatch) {
    unsigned char mapped_uuid[16];
    unsigned char file_uuid[16];
    int descriptor;
    int result = 0;
    int saved_errno = 0;

    *uuid_mismatch = 0;
    if (!titan_ls_mapped_main_uuid(mapped_uuid)) {
        errno = ENOEXEC;
        return 0;
    }
    descriptor = open(path, O_RDONLY);
    if (descriptor < 0) return 0;
    if (fstat(descriptor, metadata) != 0 ||
        !titan_ls_file_uuid(descriptor, file_uuid)) {
        saved_errno = errno;
    } else if (memcmp(mapped_uuid, file_uuid, sizeof(mapped_uuid)) != 0) {
        *uuid_mismatch = 1;
    } else {
        result = 1;
    }
    if (close(descriptor) != 0 && result) {
        result = 0;
        saved_errno = errno;
    }
    if (!result && !*uuid_mismatch) {
        errno = saved_errno != 0 ? saved_errno : ENOEXEC;
    }
    return result;
}

