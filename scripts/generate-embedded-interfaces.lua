local provider, scan_error
if windows then
    local support = require "titan"
    local driver = require "titan-compiler.driver"
    provider = { entries = {} }
    for _, name in ipairs(EXPECTED_MODULES) do
        local symbol = driver.mangle_module_name(name) .. "_abi_value"
        local abi, error = support._abivalue(archive, symbol)
        if abi ~= EXPECTED_ABI then
            script_error(name .. " ABI mismatch: " .. tostring(abi or error))
        end
        provider.entries[name] = { module = name, abi = abi }
    end
    for _, name in ipairs(EXPECTED_MODULES) do
        local symbol = driver.mangle_module_name(name) .. "_types"
        local query, error = support._loadlib(archive, symbol)
        if not query then script_error(tostring(error)) end
        provider.entries[name].types = query()
    end
else
    provider, scan_error = staticmetadata.scan_archive(archive, { expected_abi = EXPECTED_ABI })
end
if not provider then
    script_error("cannot scan canonical Titan archive: " .. tostring(scan_error))
end

local names, inventory_error = validate_inventory(provider.entries)
if not names then
    script_error(string.format("archive %q: %s", archive, inventory_error))
end

local driver = require "titan-compiler.driver"
local csemantics = require "titan-compiler.csemantics"
local types = require "titan-compiler.types"
if driver.LANGUAGE_SERVER_API_VERSION ~= 1 then
    script_error("compiler language-server API 1 is required for target profiles")
end
local context = driver.new_resolver_context()
local ok, profile, profile_error = pcall(function()
    local service, service_error = driver.get_probe_service(context)
    if not service then return nil, service_error end
    local data, export_error = csemantics.export_profile(service.profile)
    if not data then return nil, export_error end
    -- The archive and generated profile must describe the same native target.
    -- Leave all type validation and numeric trait reconstruction to the
    -- compiler, which owns both metadata formats.
    for _, name in ipairs(names) do
        local module_type, decode_error = driver.decode_module_interface(
            provider.entries[name].types, name, archive)
        if not module_type then return nil, decode_error end
        local normalized, normalize_error =
            types.normalize_portable_c_numeric_types(module_type, service.profile)
        if not normalized then return nil, name .. ": " .. normalize_error end
    end
    return data
end)
local closed, close_error = driver.close_resolver_context(context)
if not ok then
    script_error("cannot acquire build target profile: " .. tostring(profile))
elseif not profile then
    script_error("cannot acquire build target profile: " .. tostring(profile_error))
elseif not closed then
    script_error("cannot close build target resolver: " .. tostring(close_error))
end

local contents, render_error
