local function read_file(filename)
    local file = io.open(filename, "rb")
    if not file then return nil end
    local contents, read_error = file:read("*a")
    local closed, close_error = file:close()
    if contents == nil then return nil, read_error end
    if closed == nil then return nil, close_error end
    return contents
end

local function write_if_changed(filename, contents)
    local existing, read_error = read_file(filename)
    if read_error then
        return nil, "cannot read existing output " .. string.format("%q", filename) ..
            ": " .. tostring(read_error)
    elseif existing == contents then
        return true
    end

    local temporary = filename .. ".tmp"
    os.remove(temporary)
    local file, open_error = io.open(temporary, "wb")
    if not file then
        return nil, "cannot open temporary output " ..
            string.format("%q", temporary) ..
            ": " .. tostring(open_error)
    end
    local wrote, write_error = file:write(contents)
    local closed, close_error = file:close()
    if not wrote then
        os.remove(temporary)
        return nil, "cannot write temporary output " ..
            string.format("%q", temporary) ..
            ": " .. tostring(write_error)
    elseif closed == nil then
        os.remove(temporary)
        return nil, "cannot close temporary output " ..
            string.format("%q", temporary) ..
            ": " .. tostring(close_error)
    end
    if package.config:sub(1, 1) == "\\" then os.remove(filename) end
    local published, publish_error = os.rename(temporary, filename)
    if not published then
        os.remove(temporary)
        return nil, "cannot publish output " .. string.format("%q", filename) ..
            ": " .. tostring(publish_error)
    end
    return true
end

local function self_test()
    assert(byte_initializer("A\0\"\255") == "    65, 0, 34, 255,")

    local entries = {}
    for _, name in ipairs(EXPECTED_MODULES) do
        entries[name] = {
            module = name,
            abi = EXPECTED_ABI,
            types = "Module(" .. name .. ")",
        }
    end
    local profile = {
        version = 1,
        identity = "profile\0identity",
        integers = { int = { signed = true, bits = 32 } },
        floats = {},
    }
    local first = assert(render_source(entries, profile))
    local second = assert(render_source(entries, profile))
    assert(first == second)
    assert(first:find("titan_ls_push_embedded_interface_provider", 1, true))
    assert(first:find("titan_ls_push_embedded_provider_identity", 1, true))
    assert(first:find('stat("/proc/self/exe"', 1, true))
    assert(first:find("metadata.st_mtimespec.tv_nsec", 1, true))
    assert(first:find("titan_ls_mapped_main_uuid", 1, true))
    assert(first:find("LC_UUID", 1, true))
    assert(first:find("uuid_mismatch", 1, true))
    assert(first:find("lua_newuserdatauv", 1, true))
    assert(first:find("lua_pushlstring", 1, true))
