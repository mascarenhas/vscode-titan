local function script_error(message)
    io.stderr:write("generate-embedded-interfaces: ", message, "\n")
    os.exit(1)
end

local function join_quoted(values)
    local quoted = {}
    for index, value in ipairs(values) do
        quoted[index] = string.format("%q", value)
    end
    return table.concat(quoted, ", ")
end

local function validate_inventory(entries)
    if type(entries) ~= "table" then
        return nil, "archive scanner returned no metadata entry table"
    end

    local expected = {}
    for _, name in ipairs(EXPECTED_MODULES) do expected[name] = true end

    local missing = {}
    for _, name in ipairs(EXPECTED_MODULES) do
        if entries[name] == nil then missing[#missing + 1] = name end
    end

    local unexpected = {}
    for name in pairs(entries) do
        if not expected[name] then unexpected[#unexpected + 1] = name end
    end
    table.sort(unexpected)

    if #missing ~= 0 or #unexpected ~= 0 then
        local parts = {}
        if #missing ~= 0 then
            parts[#parts + 1] = "missing " .. join_quoted(missing)
        end
        if #unexpected ~= 0 then
            parts[#parts + 1] = "unexpected " .. join_quoted(unexpected)
        end
        return nil, "expected the exact " .. #EXPECTED_MODULES ..
            "-module Titan interface inventory (" ..
            table.concat(parts, "; ") .. ")"
    end

    for _, name in ipairs(EXPECTED_MODULES) do
        local entry = entries[name]
        if type(entry) ~= "table" or entry.module ~= name then
            return nil, "metadata entry " .. string.format("%q", name) ..
                " has an inconsistent logical module name"
        elseif entry.abi ~= EXPECTED_ABI then
            return nil, "metadata entry " .. string.format("%q", name) ..
                " has ABI " .. string.format("%q", tostring(entry.abi)) ..
                "; expected " .. string.format("%q", EXPECTED_ABI)
        elseif type(entry.types) ~= "string" or entry.types == "" then
            return nil, "metadata entry " .. string.format("%q", name) ..
                " has empty or non-string type metadata"
        end
    end

    return EXPECTED_MODULES
end

local function byte_initializer(value, indent)
    indent = indent or "    "
    local lines = {}
    local bytes = {}
    for index = 1, #value do
        bytes[#bytes + 1] = tostring(string.byte(value, index))
        if #bytes == 12 then
            lines[#lines + 1] = indent .. table.concat(bytes, ", ") .. ","
            bytes = {}
        end
    end
    if #bytes ~= 0 then
        lines[#lines + 1] = indent .. table.concat(bytes, ", ") .. ","
    end
    return table.concat(lines, "\n")
end

local function render_array(name, value)
    assert(value ~= "", "generated byte arrays must not be empty")
    return "static const unsigned char " .. name .. "[] = {\n" ..
        byte_initializer(value) .. "\n};\n"
end

-- The profile is declarative compiler data. Emit ordinary Lua C API pushes,
-- just like the interface inventory, without evaluating a Lua chunk at server
-- startup or retaining any build-machine SDK paths.
local function render_profile(profile)
    local declarations, statements, strings = {}, {}, {}
    local string_count, stack_slots = 0, 0
    local active = {}
    local function emit(value, depth)
        stack_slots = math.max(stack_slots, depth + 1)
        local kind = type(value)
        if kind == "string" then
            if value == "" then
                statements[#statements + 1] = '    lua_pushliteral(L, "");'
                return
            end
            local name = strings[value]
            if not name then
                string_count = string_count + 1
                name = "titan_ls_profile_string_" .. string_count
                strings[value] = name
                declarations[#declarations + 1] = render_array(name, value)
            end
            statements[#statements + 1] = string.format(
                "    titan_ls_push_bytes(L, %s, sizeof(%s));", name, name)
        elseif kind == "boolean" then
            statements[#statements + 1] = string.format(
                "    lua_pushboolean(L, %d);", value and 1 or 0)
        elseif kind == "number" then
            assert(math.type(value) == "integer", "profile number is not an integer")
            statements[#statements + 1] = string.format(
                "    lua_pushinteger(L, (lua_Integer)%d);", value)
        else
            assert(kind == "table" and getmetatable(value) == nil,
                "profile contains non-declarative data")
            assert(not active[value], "profile contains a cycle")
            active[value] = true
            local keys = {}
            for key in pairs(value) do
                assert(type(key) == "string", "profile key is not a string")
                keys[#keys + 1] = key
            end
            table.sort(keys)
            statements[#statements + 1] = string.format(
                "    lua_createtable(L, 0, %d);", #keys)
            for _, key in ipairs(keys) do
                emit(key, depth + 1)
                emit(value[key], depth + 2)
                statements[#statements + 1] = "    lua_rawset(L, -3);"
            end
            active[value] = nil
        end
    end
    emit(profile, 0)
    local body = {
        "static void titan_ls_push_target_profile(lua_State *L) {",
        string.format(
            '    luaL_checkstack(L, %d, "embedded Titan target profile");',
            stack_slots),
        table.concat(statements, "\n"),
        "}",
    }
    return table.concat(declarations, "\n"), table.concat(body, "\n")
end

